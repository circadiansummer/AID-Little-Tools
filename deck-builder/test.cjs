const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const html = fs.readFileSync(`${__dirname}/Story-Card-Deck-Builder.html`, 'utf8');
const script = [...html.matchAll(/<script>([\s\S]*?)<\/script>/g)][0][1];
new vm.Script(script);
const context = vm.createContext({ URL });
vm.runInContext(script.split('const defaults=')[0] + '\nthis.api={parseCards,parseImages,matchCard,safeImage,characterMeta,castCounts};', context);
const {parseCards, parseImages, matchCard, safeImage} = context.api;
const roster=JSON.parse(fs.readFileSync(`${__dirname}/data/roster.json`, 'utf8'));
const config=JSON.parse(fs.readFileSync(`${__dirname}/data/better-dungeons.json`, 'utf8'));
const cards=parseCards(roster), images=parseImages(config);
assert.equal(cards.length,250);
assert.equal(images.length,250);
assert.equal(cards.filter(c=>matchCard(c, images).image).length,250,'All default characters have matching portraits');
const raymond=matchCard({title:'Raymond',keys:'Raymond'},images);
assert.ok(raymond.image.startsWith('data:image/'));
assert.equal(raymond.record.name,'Raymond');
const id=matchCard({id:'aid-1',title:'Other',keys:'x'},[{name:'Original',aidId:'aid-1',graphics:['https://example.com/portrait.png']}]);
assert.equal(id.record.name,'Original');
assert.equal(matchCard({title:'Other',keys:'Raymond'},images).record.name,'Raymond');
assert.equal(matchCard({title:'Raymond',keys:'Raymond'},[...images,raymond.record]).ambiguous,true);
assert.equal(parseImages({adventures:[config.adventure,config.adventure]}).length,500);
assert.equal(safeImage('javascript:alert(1)'), '');
assert.equal(safeImage('data:image/svg+xml;base64,PHN2Zz4='), '');
const extra={keys:'one',value:'entry',title:'Preserve me',custom:{flags:[1,false,null]},isPinned:true};
const imported=parseCards({format:'story-card-studio-project/v1',cards:[extra]});
assert.equal(JSON.stringify(imported[0]),JSON.stringify(extra));
imported[0].custom.flags[0]=99;
assert.equal(extra.custom.flags[0],1);
assert.throws(()=>parseCards([{name:'Missing keys/value'}]));
assert.throws(()=>parseCards(Array(5001).fill(extra)));
assert.throws(()=>parseImages({settings:{}}));
assert.ok(!html.includes('__ROSTER__')&&!html.includes('__IMAGES__'));
console.log('PASS: syntax, real fixtures, image ID/title/trigger matching, ambiguity, backups, URL filtering, validation, nested field preservation.');
const meta=context.api.characterMeta(cards[0]);
assert.equal(meta.gender,'Male');
assert.equal(meta.species,'Cat');
assert.equal(meta.personality,'Smug');
assert.equal(meta.starSign,'Libra');
assert.equal(meta.catchphrase,'crisp');
assert.equal(context.api.characterMeta({value:''}).species,'Unknown');
assert.equal(JSON.stringify(context.api.castCounts(cards.slice(0,3),'gender')),JSON.stringify([['Female',2],['Male',1]]));
console.log('PASS: entry metadata, catchphrases, unknown fields, and cast counts');